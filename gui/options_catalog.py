def _index_options(options):
    """キー重複と未知の分類を起動前に落とす。"""
    indexed = {}
    known_groups = set(GROUPS)
    allowed_kinds = {"bool", "text", "path", "choice", "optional"}
    for spec in options:
        key = spec["key"]
        # 同じキーが二つあると、画面と引数の対応がずれる
        if key in indexed:
            raise RuntimeError("duplicate option key: " + key)
        # 分類漏れはタブに出てこないので、ここで止める
        if spec["group"] not in known_groups:
            raise RuntimeError("unknown group: " + key)
        # 描画と引数生成が知らない種別は受け付けない
        if spec["kind"] not in allowed_kinds:
            raise RuntimeError("unknown kind: " + key)
        # 選択式なのに候補が無いと、コンボが空になる
        if spec["kind"] == "choice" and not spec.get("choices"):
            raise RuntimeError("choice without values: " + key)
        indexed[key] = spec
    return indexed


OPTION_BY_KEY = _index_options(OPTIONS)

# 接続先を同時に複数指定すると scrcpy が起動できない。
SELECTOR_KEYS = ("serial", "select-usb", "select-tcpip", "tcpip")

for _catalog_key in INFO_KEYS + SELECTOR_KEYS:
    # 一覧や接続チェックが、実在しない項目を見に行かないようにする
    if _catalog_key not in OPTION_BY_KEY:
        raise RuntimeError("unknown catalog key: " + _catalog_key)
